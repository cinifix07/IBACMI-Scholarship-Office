import fs from 'node:fs/promises'
import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(pathToFileURL('C:/Users/ACER ASPIRE 3/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs'))
const base = 'http://127.0.0.1:5174/IBACMI-Scholarship-Office'
const out = 'tmp/loader-check'
await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/__loader-check', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#fcf9f8;font-family:system-ui}button,input{padding:10px;border-radius:10px;border:1px solid #e4d1c6;max-width:100%}</style></head><body><div id="root"></div><script type="module" src="/IBACMI-Scholarship-Office/tests/loaderHarness.jsx"></script></body></html>' }))
  await page.goto(base + '/__loader-check')
  await page.waitForFunction(() => window.setLoaderModel)
  const primary = page.locator('#loader-primary')
  await primary.locator('.ibacmi-loader__seal img').waitFor()
  assert.equal(await primary.getByRole('progressbar').count(), 0)
  assert.equal(await primary.locator('img').evaluate(img => img.complete && img.naturalWidth > 0), true)
  await page.evaluate(() => window.setLoaderModel({ progress: 33 }))
  await primary.getByRole('progressbar').waitFor()
  assert.equal(await primary.getByRole('progressbar').getAttribute('aria-valuenow'), '33')
  assert.equal(await primary.locator('.ibacmi-loader__arc').getAttribute('stroke-dashoffset'), '67')
  await page.evaluate(() => window.setLoaderModel({ progress: 99.9999 }))
  await page.waitForFunction(() => document.querySelector('#loader-primary [role="progressbar"]').getAttribute('aria-valuenow') === '99.9')
  await page.evaluate(() => window.setLoaderModel({ progress: 100 }))
  await primary.getByRole('progressbar').waitFor({ state: 'detached' })
  assert.doesNotMatch(await primary.innerText(), /100%/)
  await page.evaluate(() => window.setLoaderModel({ progress: 100, state: 'success', message: 'Your file is ready!' }))
  await primary.getByText('100%', { exact: true }).waitFor()
  assert.equal(await primary.locator('.ibacmi-loader__badge').count(), 1)
  await page.evaluate(() => window.setLoaderModel({}))
  await page.getByLabel('Unsaved information').fill('Preserve these unsaved changes')
  await page.evaluate(() => { document.getElementById('start-loader-task').click(); document.getElementById('start-loader-task').click() })
  await page.waitForFunction(() => window.updateLoaderTask)
  assert.equal(await page.evaluate(() => window.loaderTaskCalls), 1)
  await page.evaluate(() => window.updateLoaderTask({ progress: 45 }))
  const operation = page.locator('#loader-operation')
  await operation.getByText('45%', { exact: true }).waitFor()
  await page.evaluate(() => window.failLoaderTask(new Error('Isolated test transfer failed.')))
  await operation.getByRole('button', { name: 'Retry', exact: true }).waitFor()
  assert.equal(await operation.locator('.ibacmi-loader__arc').evaluate(el => getComputedStyle(el).animationName), 'none')
  assert.equal(await page.getByLabel('Unsaved information').inputValue(), 'Preserve these unsaved changes')
  await operation.getByRole('button', { name: 'Retry', exact: true }).click()
  await page.waitForFunction(() => window.loaderTaskCalls === 2)
  await page.getByRole('button', { name: 'Show file status dialog', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'File preparation status' })
  await dialog.waitFor()
  await page.screenshot({ path: out + '/desktop-modal.png' })
  for (const viewport of [{ width: 390, height: 844 }, { width: 320, height: 568 }]) {
    await page.setViewportSize(viewport)
    const box = await dialog.boundingBox()
    assert.ok(box.x >= 0 && box.y >= 0 && box.x + box.width <= viewport.width + 1 && box.y + box.height <= viewport.height + 1)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }
  await page.screenshot({ path: out + '/mobile-modal.png' })
  await page.getByRole('button', { name: 'Continue in background' }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.evaluate(() => window.completeLoaderTask())
  await operation.getByText('Your file is ready!', { exact: true }).waitFor()
  await operation.getByText('100%', { exact: true }).waitFor()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const animations = await primary.locator('.ibacmi-loader__arc,.ibacmi-loader__seal,.ibacmi-loader__seal img').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).animationName))
  assert.ok(animations.every(name => name === 'none'))
  await page.screenshot({ path: out + '/mobile-section.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: out + '/desktop-section.png' })
  assert.deepEqual(errors, [])
  console.log('PASS loader: official logo, indeterminate/determinate/success semantics, no premature 100% or rounding to 100%, actual task lifecycle, duplicate protection, error/retry preserving form input, background continuation, reduced motion, desktop/mobile and short-viewport modal.')
} finally { await browser.close() }
