  assert.equal(data.tables.studentProfileSubmissions.length, 2)
  assert.equal(data.account.studentInformation.yearLevelCode, 3)
  await page.screenshot({ path: `${out}/submitted-modal-desktop.png` })
  assert.deepEqual(errors, [])
  console.log('PASS desktop/mobile: ID upload required for 100%, real upload metadata and annual submission handlers, submitted modal, locked profile/uploads after reload, new official year reopens editing and requires a new ID; no browser errors. External Drive transfer uses an isolated PDF fixture.')
